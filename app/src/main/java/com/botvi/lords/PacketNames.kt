    fun nameOf(id: Int): String? = names[id]

    fun idOf(p: ByteArray): Int =
        if (p.size < 2) -1 else (p[0].toInt() and 0xFF) or ((p[1].toInt() and 0xFF) shl 8)

    /** "2220 RESP_UPDATE_MAPINFO_PLUS" or just the number when unknown. */
    fun label(id: Int): String = if (id < 0) "" else id.toString() + (names[id]?.let { " $it" } ?: "")

    /** [key] is the stats key like "AC 08 0C" (hex bytes). */
    fun labelForKey(key: String): String {
        val parts = key.split(' ')
        if (parts.size < 2) return ""
        val b0 = parts[0].toIntOrNull(16) ?: return ""
        val b1 = parts[1].toIntOrNull(16) ?: return ""
        return label(b0 or (b1 shl 8))
    }
